#!/usr/bin/env node
/**
 * Generate supabase/migrations/20260920120100_seed_ads.sql from the legacy
 * hard-coded affiliate config (components/monetization/affiliates.ts and
 * ad-copy.ts).
 *
 * Usage (Node 22.18+ strips TypeScript types natively):
 *   node scripts/generate-ads-seed.mjs
 *
 * The output is idempotent: advertisers/placements upsert on slug, campaigns
 * upsert on their deterministic `slug`, creatives upsert on `seed_key`.
 * Re-running the SQL refreshes copy + targeting but leaves admin-managed state
 * (campaign status/weight, advertiser is_active/notes) untouched.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'supabase/migrations/20260920120100_seed_ads.sql');

const { affiliates, contextAffiliates } = await import(
  path.join(ROOT, 'components/monetization/affiliates.ts')
);
const { affiliateAdCopy } = await import(path.join(ROOT, 'components/monetization/ad-copy.ts'));

// ---------------------------------------------------------------------------
// Config
// ---------------------------------------------------------------------------
const PLACEMENTS = [
  { slug: 'tool-inline-top', name: 'Tool — inline top', formats: ['leaderboard', 'mobile_banner'], rotation: 15000 },
  { slug: 'tool-below-results', name: 'Tool — below results', formats: ['large_rectangle'], rotation: 12000 },
  { slug: 'tool-sidebar', name: 'Tool — sidebar', formats: ['medium_rectangle'], rotation: 15000 },
];
const SEED_PLACEMENT = 'tool-inline-top';

const FORMAT_MAP = {
  mediumRectangle: 'medium_rectangle',
  leaderboard: 'leaderboard',
  mobileBanner: 'mobile_banner',
  largeRectangle: 'large_rectangle',
};

// Tools that had no contextAffiliates mapping (and therefore showed nothing).
// Give them a sensible default rotation.
const UNMAPPED_TOOLS = ['coast-fire', 'capital-gains-tax', 'gambling-redirect'];
const UNMAPPED_TOOL_ADVERTISERS = ['sofi', 'rocket-money', 'rakuten'];

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (items) => (items.length ? `array[${items.map(q).join(', ')}]::text[]` : `'{}'::text[]`);

// ---------------------------------------------------------------------------
// Derive campaign targeting from contextAffiliates
// ---------------------------------------------------------------------------
const toolsByAdvertiser = new Map(); // advertiserId -> Set<toolId>
const primaryAdvertisers = new Set();
for (const [toolId, ctx] of Object.entries(contextAffiliates)) {
  const list = ctx.rotating && ctx.rotating.length ? ctx.rotating : [ctx.primary];
  for (const a of list) {
    if (!toolsByAdvertiser.has(a.id)) toolsByAdvertiser.set(a.id, new Set());
    toolsByAdvertiser.get(a.id).add(toolId);
  }
  if (ctx.primary) {
    if (!toolsByAdvertiser.has(ctx.primary.id)) toolsByAdvertiser.set(ctx.primary.id, new Set());
    toolsByAdvertiser.get(ctx.primary.id).add(toolId);
    primaryAdvertisers.add(ctx.primary.id);
  }
}
for (const advId of UNMAPPED_TOOL_ADVERTISERS) {
  if (!toolsByAdvertiser.has(advId)) toolsByAdvertiser.set(advId, new Set());
  for (const t of UNMAPPED_TOOLS) toolsByAdvertiser.get(advId).add(t);
}

// ---------------------------------------------------------------------------
// Emit SQL
// ---------------------------------------------------------------------------
const lines = [];
const counts = { placements: 0, advertisers: 0, campaigns: 0, creatives: 0 };

lines.push('-- GENERATED by scripts/generate-ads-seed.mjs — do not edit by hand.');
lines.push('-- Seeds the ads tables from the legacy affiliates.ts / ad-copy.ts config.');
lines.push('-- Requires 20260920120000_create_ads_tables.sql. Safe to re-run.');
lines.push('');
lines.push('begin;');
lines.push('');
lines.push('-- ---------------------------------------------------------------');
lines.push('-- Placements');
lines.push('-- ---------------------------------------------------------------');
for (const p of PLACEMENTS) {
  lines.push(
    `insert into public.ad_placements (slug, name, formats, rotation_interval_ms, is_active) values (` +
      `${q(p.slug)}, ${q(p.name)}, ${arr(p.formats)}, ${p.rotation}, true) ` +
      `on conflict (slug) do update set name = excluded.name, formats = excluded.formats, ` +
      `rotation_interval_ms = excluded.rotation_interval_ms;`,
  );
  counts.placements++;
}

lines.push('');
lines.push('-- ---------------------------------------------------------------');
lines.push('-- Advertisers');
lines.push('-- ---------------------------------------------------------------');
const advertiserList = Object.values(affiliates);
for (const a of advertiserList) {
  lines.push(
    `insert into public.ad_advertisers (slug, name, url, description, tagline, cta, category, is_active) values (` +
      `${q(a.id)}, ${q(a.name)}, ${q(a.url)}, ${q(a.description ?? null)}, ${q(a.tagline ?? null)}, ` +
      `${q(a.cta ?? null)}, ${q(a.category)}, true) ` +
      `on conflict (slug) do update set name = excluded.name, url = excluded.url, ` +
      `description = excluded.description, tagline = excluded.tagline, cta = excluded.cta, ` +
      `category = excluded.category;`,
  );
  counts.advertisers++;
}

lines.push('');
lines.push('-- ---------------------------------------------------------------');
lines.push('-- Campaigns (one active campaign per advertiser on tool-inline-top)');
lines.push('-- ---------------------------------------------------------------');
const campaignSlugFor = (advId) => `${advId}-${SEED_PLACEMENT}`;
for (const a of advertiserList) {
  const tools = [...(toolsByAdvertiser.get(a.id) ?? [])].sort();
  const priority = primaryAdvertisers.has(a.id) ? 10 : 0;
  const slug = campaignSlugFor(a.id);
  lines.push(
    `insert into public.ad_campaigns (slug, advertiser_id, placement_id, name, status, tool_ids, exclude_tool_ids, weight, priority, hide_for_tiers) ` +
      `select ${q(slug)}, a.id, p.id, ${q(`${a.name} — inline top`)}, 'active', ${arr(tools)}, '{}'::text[], 1, ${priority}, '{finance_pro}'::text[] ` +
      `from public.ad_advertisers a, public.ad_placements p where a.slug = ${q(a.id)} and p.slug = ${q(SEED_PLACEMENT)} ` +
      `on conflict (slug) do update set name = excluded.name, advertiser_id = excluded.advertiser_id, ` +
      `placement_id = excluded.placement_id, tool_ids = excluded.tool_ids, priority = excluded.priority;`,
  );
  counts.campaigns++;
}

lines.push('');
lines.push('-- ---------------------------------------------------------------');
lines.push('-- Creatives (all formats attached to the advertiser campaign)');
lines.push('-- ---------------------------------------------------------------');
for (const a of advertiserList) {
  const set = affiliateAdCopy[a.id];
  if (!set) {
    console.warn(`No ad copy for ${a.id}; skipping creatives`);
    continue;
  }
  const slug = campaignSlugFor(a.id);
  for (const [legacyFormat, dbFormat] of Object.entries(FORMAT_MAP)) {
    const copies = set[legacyFormat] ?? [];
    copies.forEach((c, i) => {
      const seedKey = `${slug}:${dbFormat}:${i}`;
      lines.push(
        `insert into public.ad_creatives (campaign_id, seed_key, format, headline, body, body_line2, cta, weight, is_active) ` +
          `select c.id, ${q(seedKey)}, ${q(dbFormat)}, ${q(c.headline)}, ${q(c.body ?? null)}, ${q(c.bodyLine2 ?? null)}, ${q(c.cta)}, 1, true ` +
          `from public.ad_campaigns c where c.slug = ${q(slug)} ` +
          `on conflict (seed_key) do update set campaign_id = excluded.campaign_id, format = excluded.format, ` +
          `headline = excluded.headline, body = excluded.body, body_line2 = excluded.body_line2, cta = excluded.cta;`,
      );
      counts.creatives++;
    });
  }
}

lines.push('');
lines.push('commit;');
lines.push('');
lines.push(
  `-- Totals: ${counts.placements} placements, ${counts.advertisers} advertisers, ` +
    `${counts.campaigns} campaigns, ${counts.creatives} creatives`,
);
lines.push('');

writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${path.relative(ROOT, OUT)}`);
console.log(counts);
